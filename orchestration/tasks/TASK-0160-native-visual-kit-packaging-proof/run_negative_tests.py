#!/usr/bin/env python3
"""TASK-0160 negative-test harness for native/tools/verify_native_visual_kit.py.

Runs the committed visual-kit validator against focused synthetic fixtures
under ./fixtures (a positive mini kit plus one mutation per contract rule),
plus an independent hand-written golden-oracle test of the generator layout,
a determinism test, a read-only proof for --check, and regeneration-mode
controls. Python 3 stdlib only; never touches the network or any port.
"""

