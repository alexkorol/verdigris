import importlib.util
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[2]
TOOL_PATH = REPO_ROOT / "native" / "tools" / "verify_native_visual_kit.py"
FIXTURES_DIR = HERE / "fixtures"

